/** Map a stored social label to its icon. Unknown labels get a generic dot. */
export function SocialIcon({ label, ...props }: IconProps & { label: string }) {
  const key = label.toLowerCase();
  if (key.includes("facebook")) return <FacebookIcon {...props} />;
  if (key.includes("instagram")) return <InstagramIcon {...props} />;
  if (key.includes("twitter") || key === "x") return <XIcon {...props} />;
  if (key.includes("linkedin")) return <LinkedInIcon {...props} />;
  if (key.includes("tiktok")) return <TikTokIcon {...props} />;
  return (
    <svg {...base} {...props}>
      <circle cx="12" cy="12" r="9" />
    </svg>
  );
}
