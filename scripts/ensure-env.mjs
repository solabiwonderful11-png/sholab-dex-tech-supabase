#!/usr/bin/env node
/**
 * Guarantee the build has the public Supabase configuration.
 *
 * WHY THIS EXISTS
 * ---------------
 * Vite inlines `import.meta.env.VITE_*` at BUILD time. If the host (Vercel,
 * Netlify, CI) has no environment variables set, the bundle is built with
 * `undefined` for every one of them. `client/src/lib/supabase.ts` used to throw
 * at module load in that case, which killed the entry chunk before React could
 * mount — the deployed site was a blank white page with the error only in the
 * console.
 *
 * The values below are the *publishable* (anon) key and project URL. They are
 * designed to be public: they ship in the browser bundle by design and Row
 * Level Security is what protects the data. They are already committed in
 * `.env.example` and documented in the README, so writing them into a build
 * env file leaks nothing new.
 *
 * Precedence (highest first):
 *   1. Real environment variables from the host / shell  — always win
 *   2. An existing .env / .env.local / .env.production   — left untouched
 *   3. The defaults below                                — last resort
 *
 * The script only ever CREATES a missing file. It never overwrites one, so a
 * developer's local `.env` is safe.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Public, non-secret defaults. Safe to commit — see the note above. */
const DEFAULTS = {
  VITE_SUPABASE_URL: "https://suycnxrvnjhmjokxxbjx.supabase.co",
  VITE_SUPABASE_ANON_KEY: "sb_publishable_RO66cKGx94aBw-kB43f9Mg_4W9-sX0d",
  VITE_SUPABASE_BUCKET: "site-media",
  VITE_ADMIN_PATH: "sholab",
  VITE_ADMIN_REQUIRE_AUTH: "false",
  VITE_SITE_URL: "https://sholab-dex-tech-supabase.vercel.app",
};

/** Files Vite reads, in the order it reads them. */
const ENV_FILES = [".env", ".env.local", ".env.production", ".env.production.local"];

/** Parse a dotenv file into a plain object. Tolerant of quotes and comments. */
function parseEnv(text) {
  const out = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (key) out[key] = value;
  }
  return out;
}

/** Everything already available, host env first, then the dotenv files. */
const available = { ...DEFAULTS };
for (const file of ENV_FILES) {
  const path = resolve(root, file);
  if (!existsSync(path)) continue;
  Object.assign(available, parseEnv(readFileSync(path, "utf8")));
}
for (const key of Object.keys(DEFAULTS)) {
  const fromHost = process.env[key];
  if (fromHost && fromHost.trim()) available[key] = fromHost.trim();
}

const missing = Object.entries(available).filter(([, v]) => !v || !String(v).trim());

if (missing.length > 0) {
  console.error(
    "[ensure-env] These values are still empty and the site would not render:\n" +
      missing.map(([k]) => `  • ${k}`).join("\n"),
  );
  process.exit(1);
}

/**
 * Write `.env.production` only when no env file exists at all. Vite loads it
 * for `vite build`, so the bundle always carries a working configuration.
 */
const hasAnyEnvFile = ENV_FILES.some((f) => existsSync(resolve(root, f)));

if (hasAnyEnvFile) {
  console.log("[ensure-env] OK — an env file already exists, leaving it untouched.");
} else {
  const body =
    "# Generated by scripts/ensure-env.mjs at build time.\n" +
    "# Public (publishable) values only — never put a service_role key here.\n" +
    Object.entries(available)
      .map(([k, v]) => `${k}=${v}`)
      .join("\n") +
    "\n";
  writeFileSync(resolve(root, ".env.production"), body, "utf8");
  console.log("[ensure-env] OK — wrote .env.production with the public defaults.");
}

// Report which values the build will actually use, so a misconfiguration is
// visible in the deploy log instead of only in the browser console.
console.log(
  `[ensure-env] VITE_SUPABASE_URL=${available.VITE_SUPABASE_URL}\n` +
    `[ensure-env] VITE_SITE_URL=${available.VITE_SITE_URL}\n` +
    `[ensure-env] VITE_ADMIN_PATH=${available.VITE_ADMIN_PATH}`,
);
